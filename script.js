// ==========================================================================
// SCROLL REVEAL
// ==========================================================================

function initScrollReveal() {

    const elements =
        document.querySelectorAll(
            ".scroll-reveal"
        );


    if (
        !elements.length
    ) {

        return;

    }


    const observer =
        new IntersectionObserver(

            entries => {

                entries.forEach(
                    entry => {

                        if (
                            entry.isIntersecting
                        ) {

                            entry.target.classList.add(
                                "active"
                            );


                            observer.unobserve(
                                entry.target
                            );

                        }

                    }
                );

            },

            {
                threshold: 0.1
            }

        );


    elements.forEach(
        element => {

            observer.observe(
                element
            );

        }
    );

}


