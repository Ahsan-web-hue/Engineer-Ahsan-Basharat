const VALID_THEMES = [
    "cyan",
    "emerald",
    "purple",
    "amber"
];


// ======================================================
// Apply Accent Theme
// ======================================================

function applyTheme(theme) {

    if (
        !VALID_THEMES.includes(theme)
    ) {
        theme = "cyan";
    }


    document.documentElement
        .setAttribute(
            "data-theme",
            theme
        );


    localStorage.setItem(
        "portfolio_theme",
        theme
    );


    updateActiveThemeButton(
        theme
    );
}


// ======================================================
// Active Theme Button
// ======================================================

function updateActiveThemeButton(
    theme
) {

    document
        .querySelectorAll(
            "#customizer-panel [data-theme]"
        )
        .forEach(button => {

            const active =
                button.dataset.theme ===
                theme;


            button.classList.toggle(
                "ring-2",
                active
            );

            button.classList.toggle(
                "ring-white",
                active
            );

            button.classList.toggle(
                "scale-105",
                active
            );

            button.setAttribute(
                "aria-pressed",
                active
            );

        });
}


// ======================================================
// Load Saved Theme
// ======================================================

function initSavedTheme() {

    const savedTheme =
        localStorage.getItem(
            "portfolio_theme"
        ) || "cyan";


    applyTheme(
        savedTheme
    );
}


// ==========================================================================
// DARK / LIGHT MODE
// ==========================================================================

function applyMode(mode) {

    const html =
        document.documentElement;

    const modeButton =
        document.getElementById(
            "mode-toggle"
        );


    if (
        mode === "light"
    ) {

        html.classList.add(
            "light-mode"
        );

        html.classList.remove(
            "dark"
        );


        if (modeButton) {

            modeButton.innerHTML = `
                <i class="fa-solid fa-sun text-amber-400"></i>
                <span>Toggle Light Mode</span>
            `;

        }

    } else {

        html.classList.remove(
            "light-mode"
        );

        html.classList.add(
            "dark"
        );


        if (modeButton) {

            modeButton.innerHTML = `
                <i class="fa-solid fa-moon theme-text"></i>
                <span>Toggle Dark Mode</span>
            `;

        }

    }


    localStorage.setItem(
        "portfolio_mode",
        mode
    );
}


// ======================================================
// Toggle Dark / Light
// ======================================================

function toggleColorMode() {

    const isLight =
        document.documentElement
            .classList
            .contains(
                "light-mode"
            );


    applyMode(
        isLight
            ? "dark"
            : "light"
    );
}


// ==========================================================================
// INTRO / LOADING ANIMATION
// ==========================================================================

function initIntroAnimation() {

    const quote =
        document.getElementById(
            "intro-quote"
        );

    const name =
        document.getElementById(
            "intro-name"
        );

    const loader =
        document.getElementById(
            "intro-loader"
        );

    const introUserName =
        document.getElementById(
            "intro-user-name"
        );

    const loadingBar =
        document.getElementById(
            "loading-bar"
        );

    const loadingPercentage =
        document.getElementById(
            "loading-percentage"
        );

    const introScreen =
        document.getElementById(
            "intro-screen"
        );

    const mainPortfolio =
        document.getElementById(
            "main-portfolio"
        );


    if (
        !introScreen ||
        !mainPortfolio
    ) {
        return;
    }


    introUserName.textContent =
        portfolioData.personal.name;


    const reducedMotion =
        window.matchMedia(
            "(prefers-reduced-motion: reduce)"
        ).matches;


    if (reducedMotion) {

        introScreen.classList.add(
            "hidden"
        );

        mainPortfolio.classList.remove(
            "hidden",
            "opacity-0"
        );

        return;
    }


    // --------------------------------------------------
    // Initial state
    // --------------------------------------------------

    quote.classList.add(
        "opacity-0",
        "translate-y-6"
    );

    name.classList.add(
        "opacity-0",
        "translate-y-8"
    );

    loader.classList.add(
        "opacity-0"
    );


    // --------------------------------------------------
    // Quote
    // --------------------------------------------------

    setTimeout(
        () => {

            quote.classList.remove(
                "opacity-0",
                "translate-y-6"
            );

        },
        350
    );


    // --------------------------------------------------
    // Name
    // --------------------------------------------------

    setTimeout(
        () => {

            name.classList.remove(
                "opacity-0",
                "translate-y-8"
            );

        },
        1100
    );


    // --------------------------------------------------
    // Loader
    // --------------------------------------------------

    setTimeout(
        () => {

            loader.classList.remove(
                "opacity-0"
            );

        },
        1750
    );


    // --------------------------------------------------
    // Progress
    // --------------------------------------------------

    setTimeout(
        () => {

            const startTime =
                performance.now();

            const duration =
                2200;


            function updateProgress(
                currentTime
            ) {

                const elapsed =
                    currentTime -
                    startTime;


                const raw =
                    Math.min(
                        elapsed /
                        duration,
                        1
                    );


                const eased =
                    1 -
                    Math.pow(
                        1 - raw,
                        3
                    );


                const progress =
                    Math.round(
                        eased * 100
                    );


                loadingBar.style.width =
                    `${progress}%`;


                loadingPercentage.textContent =
                    `${progress}%`;


                if (
                    raw < 1
                ) {

                    requestAnimationFrame(
                        updateProgress
                    );

                } else {

                    finishIntro();

                }

            }


            requestAnimationFrame(
                updateProgress
            );

        },
        1950
    );


    // --------------------------------------------------
    // Finish
    // --------------------------------------------------

    function finishIntro() {

        setTimeout(
            () => {

                introScreen.classList.add(
                    "intro-exit"
                );


                setTimeout(
                    () => {

                        introScreen.classList.add(
                            "hidden"
                        );


                        mainPortfolio.classList.remove(
                            "hidden"
                        );


                        requestAnimationFrame(
                            () => {

                                mainPortfolio.classList.remove(
                                    "opacity-0"
                                );

                            }
                        );

                    },
                    850
                );

            },
            450
        );

    }

}


