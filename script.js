// ==========================================================================
// PREMIUM CIRCUIT CANVAS
// ==========================================================================

function initCircuitCanvas() {

    const canvas =
        document.getElementById(
            "circuit-canvas"
        );


    if (!canvas) {
        return;
    }


    const ctx =
        canvas.getContext(
            "2d"
        );


    let width = 0;
    let height = 0;


    function resize() {

        const dpr =
            Math.min(
                window.devicePixelRatio || 1,
                2
            );


        width =
            window.innerWidth;

        height =
            window.innerHeight;


        canvas.width =
            width * dpr;

        canvas.height =
            height * dpr;


        canvas.style.width =
            `${width}px`;

        canvas.style.height =
            `${height}px`;


        ctx.setTransform(
            dpr,
            0,
            0,
            dpr,
            0,
            0
        );

    }


    window.addEventListener(
        "resize",
        resize
    );


    resize();


    // --------------------------------------------------
    // Nodes
    // --------------------------------------------------

    const nodeCount =
        window.innerWidth < 768
            ? 28
            : 55;


    const nodes =
        Array.from(
            {
                length:
                    nodeCount
            },
            () => ({

                x:
                    Math.random()
                    * width,

                y:
                    Math.random()
                    * height,

                vx:
                    (Math.random() - 0.5)
                    * 0.18,

                vy:
                    (Math.random() - 0.5)
                    * 0.18,

                radius:
                    Math.random()
                    * 1.5 + 1,

                pulse:
                    Math.random()
                    * Math.PI * 2

            })
        );


    // --------------------------------------------------
    // Signal particles
    // --------------------------------------------------

    const signals = [];


    function createSignal() {

        const node =
            nodes[
                Math.floor(
                    Math.random()
                    * nodes.length
                )
            ];


        signals.push({

            x:
                node.x,

            y:
                node.y,

            life:
                0,

            maxLife:
                80 +
                Math.random() * 100

        });

    }


    // --------------------------------------------------
    // Theme Color Helpers
    // --------------------------------------------------

    function getThemeColor(
        variable
    ) {

        return getComputedStyle(
            document.documentElement
        )
            .getPropertyValue(
                variable
            )
            .trim();

    }


    // --------------------------------------------------
    // Animation
    // --------------------------------------------------

    function animate(
        time
    ) {

        ctx.clearRect(
            0,
            0,
            width,
            height
        );


        const primary =
            getThemeColor(
                "--brand-500"
            );


        const accent =
            getThemeColor(
                "--brand-accent"
            );


        // ------------------------------------------------
        // Update Nodes
        // ------------------------------------------------

        nodes.forEach(
            node => {

                node.x +=
                    node.vx;

                node.y +=
                    node.vy;

                node.pulse +=
                    0.025;


                if (
                    node.x < 0 ||
                    node.x > width
                ) {

                    node.vx *= -1;

                }


                if (
                    node.y < 0 ||
                    node.y > height
                ) {

                    node.vy *= -1;

                }

            }
        );


        // ------------------------------------------------
        // Connections
        // ------------------------------------------------

        for (
            let i = 0;
            i < nodes.length;
            i++
        ) {

            const a =
                nodes[i];


            for (
                let j = i + 1;
                j < nodes.length;
                j++
            ) {

                const b =
                    nodes[j];


                const distance =
                    Math.hypot(
                        a.x - b.x,
                        a.y - b.y
                    );


                if (
                    distance < 145
                ) {

                    const opacity =
                        (
                            1 -
                            distance / 145
                        ) * 0.28;


                    ctx.beginPath();


                    ctx.moveTo(
                        a.x,
                        a.y
                    );


                    ctx.lineTo(
                        b.x,
                        b.y
                    );


                    ctx.strokeStyle =
                        hexToRgba(
                            primary,
                            opacity
                        );


                    ctx.lineWidth =
                        0.7;


                    ctx.stroke();

                }

            }

        }


        // ------------------------------------------------
        // Nodes
        // ------------------------------------------------

        nodes.forEach(
            node => {

                const pulse =
                    (
                        Math.sin(
                            node.pulse
                        ) + 1
                    ) / 2;


                ctx.beginPath();


                ctx.arc(
                    node.x,
                    node.y,
                    node.radius +
                    pulse * 1.2,
                    0,
                    Math.PI * 2
                );


                ctx.fillStyle =
                    accent;


                ctx.shadowBlur =
                    12;


                ctx.shadowColor =
                    primary;


                ctx.fill();


                ctx.shadowBlur =
                    0;

            }
        );


        // ------------------------------------------------
        // Signals
        // ------------------------------------------------

        signals.forEach(
            signal => {

                signal.life++;


                const alpha =
                    1 -
                    signal.life /
                    signal.maxLife;


                ctx.beginPath();


                ctx.arc(
                    signal.x,
                    signal.y,
                    2.5,
                    0,
                    Math.PI * 2
                );


                ctx.fillStyle =
                    `rgba(255,255,255,${alpha})`;


                ctx.shadowBlur =
                    18;


                ctx.shadowColor =
                    primary;


                ctx.fill();


                ctx.shadowBlur =
                    0;

            }
        );


        // ------------------------------------------------
        // Remove old signals
        // ------------------------------------------------

        for (
            let i =
                signals.length - 1;

            i >= 0;

            i--
        ) {

            if (
                signals[i].life >
                signals[i].maxLife
            ) {

                signals.splice(
                    i,
                    1
                );

            }

        }


        // ------------------------------------------------
        // Random signal
        // ------------------------------------------------

        if (
            Math.random() <
            0.025
        ) {

            createSignal();

        }


        requestAnimationFrame(
            animate
        );

    }


    requestAnimationFrame(
        animate
    );

}


// ==========================================================================
// HEX TO RGBA
// ==========================================================================

function hexToRgba(
    hex,
    alpha
) {

    if (
        !hex
    ) {

        return `
            rgba(
                6,
                182,
                212,
                ${alpha}
            )
        `;

    }


    hex =
        hex.replace(
            "#",
            ""
        );


    if (
        hex.length === 3
    ) {

        hex =
            hex
                .split("")
                .map(
                    char =>
                        char + char
                )
                .join("");

    }


    const bigint =
        parseInt(
            hex,
            16
        );


    const r =
        (bigint >> 16)
        & 255;


    const g =
        (bigint >> 8)
        & 255;


    const b =
        bigint & 255;


    return `
        rgba(
            ${r},
            ${g},
            ${b},
            ${alpha}
        )
    `;
}


